void lcd_init(void)
{
    spi_bus_config_t bus = {
        .mosi_io_num     = LCD_PIN_MOSI,
        .miso_io_num     = -1,
        .sclk_io_num     = LCD_PIN_CLK,
        .quadwp_io_num   = -1,
        .quadhd_io_num   = -1,
        .max_transfer_sz = LCD_WIDTH * CHAR_H * 2 + 64,
    };
    esp_err_t err = spi_bus_initialize(LCD_SPI_HOST, &bus, SPI_DMA_CH_AUTO);
    if (err != ESP_OK && err != ESP_ERR_INVALID_STATE) {
        ESP_LOGW(TAG, "LCD SPI bus init failed: %s", esp_err_to_name(err));
        return;
    }

    esp_lcd_panel_io_spi_config_t io_cfg = {
        .cs_gpio_num     = LCD_PIN_CS,
        .dc_gpio_num     = LCD_PIN_DC,
        .spi_mode        = 0,
        .pclk_hz         = 40 * 1000 * 1000,
        .trans_queue_depth = 10,
        .lcd_cmd_bits    = 8,
        .lcd_param_bits  = 8,
    };
    if (esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)LCD_SPI_HOST,
                                  &io_cfg, &s_io) != ESP_OK) {
        ESP_LOGW(TAG, "LCD panel IO init failed");
        return;
    }

    gpio_set_direction(LCD_PIN_RST, GPIO_MODE_OUTPUT);
    gpio_set_level(LCD_PIN_RST, 0);
    vTaskDelay(pdMS_TO_TICKS(10));
    gpio_set_level(LCD_PIN_RST, 1);
    vTaskDelay(pdMS_TO_TICKS(120));

    const uint8_t *p = st7735_init_cmds;
    while (*p) {
        uint8_t cmd = *p++;
        if (cmd == 0xFF) {
            vTaskDelay(pdMS_TO_TICKS(*p++));
            continue;
        }
        uint8_t argc = *p++;
        if (argc > 0) {
            st7735_send_cmd_data(cmd, p, argc);
            p += argc;
        } else {
            st7735_send_cmd(cmd);
        }
    }

    ledc_timer_config_t lt = {
        .speed_mode      = LEDC_LOW_SPEED_MODE,
        .timer_num       = LEDC_TIMER_1,
        .duty_resolution = LEDC_TIMER_8_BIT,
        .freq_hz         = 1000,
        .clk_cfg         = LEDC_AUTO_CLK,
    };
    ledc_timer_config(&lt);
    ledc_channel_config_t lc = {
        .speed_mode = LEDC_LOW_SPEED_MODE,
        .channel    = LEDC_CHANNEL_3,
        .timer_sel  = LEDC_TIMER_1,
        .gpio_num   = LCD_PIN_BL,
        .duty       = 128,
        .hpoint     = 0,
    };
    ledc_channel_config(&lc);

    s_mutex = xSemaphoreCreateMutex();
    s_ok = true;

    uint16_t black = rgb565(0, 0, 0);
    for (int i = 0; i < LCD_WIDTH * CHAR_H; i++) s_row_buf[i] = black;
    for (int y = 0; y < LCD_HEIGHT; y += CHAR_H) {
        int h = (y + CHAR_H > LCD_HEIGHT) ? LCD_HEIGHT - y : CHAR_H;
        st7735_set_window(0, y, LCD_WIDTH - 1, y + h - 1);
        esp_lcd_panel_io_tx_color(s_io, 0x2C, s_row_buf, LCD_WIDTH * h * 2);
    }

    ESP_LOGI(TAG, "ST7735 160x80 LCD ready");
}

void lcd_update(const char *line1, const char *line2,
                const char *line3, const char *line4)
{
    if (!s_ok) return;
    if (xSemaphoreTake(s_mutex, pdMS_TO_TICKS(1000)) != pdTRUE) return;

    uint16_t white = rgb565(255, 255, 255);
    uint16_t green = rgb565(0, 200, 0);
    uint16_t blue  = rgb565(60, 120, 255);
    uint16_t black = rgb565(0, 0, 0);
    uint16_t dim   = rgb565(120, 120, 120);

    render_line(0, line1, white, black);
    render_line(1, line2, green, black);
    render_line(2, line3, dim, black);
    render_line(3, line4, blue, black);

    xSemaphoreGive(s_mutex);
}
