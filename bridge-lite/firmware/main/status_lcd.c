#define CHAR_W  12
#define CHAR_H  20
#define COLS    (LCD_WIDTH / CHAR_W)

static uint16_t s_row_buf[LCD_WIDTH * CHAR_H];

static uint16_t rgb565(uint8_t r, uint8_t g, uint8_t b)
{
    uint16_t c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
    return (c >> 8) | (c << 8);
}

static void st7735_send_cmd(uint8_t cmd)
{
    esp_lcd_panel_io_tx_param(s_io, cmd, NULL, 0);
}

static void st7735_send_cmd_data(uint8_t cmd, const uint8_t *data, int len)
{
    esp_lcd_panel_io_tx_param(s_io, cmd, data, len);
}

#define GAP_X   1
#define GAP_Y  26

static void st7735_set_window(int x0, int y0, int x1, int y1)
{
    int cx0 = x0 + GAP_X, cx1 = x1 + GAP_X;
    int ry0 = y0 + GAP_Y, ry1 = y1 + GAP_Y;
    uint8_t ca[] = {(uint8_t)(cx0>>8),(uint8_t)cx0,(uint8_t)(cx1>>8),(uint8_t)cx1};
    uint8_t ra[] = {(uint8_t)(ry0>>8),(uint8_t)ry0,(uint8_t)(ry1>>8),(uint8_t)ry1};
    st7735_send_cmd_data(0x2A, ca, 4);
    st7735_send_cmd_data(0x2B, ra, 4);
}

static void render_line(int row, const char *text, uint16_t fg, uint16_t bg)
{
    if (!s_ok) return;

    int y0 = row * CHAR_H;
    st7735_set_window(0, y0, LCD_WIDTH - 1, y0 + CHAR_H - 1);

    int len = text ? (int)strlen(text) : 0;
    for (int i = 0; i < LCD_WIDTH * CHAR_H; i++)
        s_row_buf[i] = bg;

    for (int ci = 0; ci < COLS && ci < len; ci++) {
        unsigned char ch = (unsigned char)text[ci];
        if (ch < 32 || ch > 126) ch = ' ';
        const uint8_t *glyph = font5x8[ch - 32];
        int x0 = ci * CHAR_W;
        for (int col = 0; col < 5; col++) {
            uint8_t bits = glyph[col];
            for (int bit = 0; bit < 8; bit++) {
                if (bits & (1 << bit)) {
                    int px = x0 + col * 2;
                    int py = bit * 2 + 2;
                    s_row_buf[py       * LCD_WIDTH + px]     = fg;
                    s_row_buf[py       * LCD_WIDTH + px + 1] = fg;
                    s_row_buf[(py + 1) * LCD_WIDTH + px]     = fg;
                    s_row_buf[(py + 1) * LCD_WIDTH + px + 1] = fg;
                }
            }
        }
    }

    esp_lcd_panel_io_tx_color(s_io, 0x2C, s_row_buf, LCD_WIDTH * CHAR_H * 2);
}

